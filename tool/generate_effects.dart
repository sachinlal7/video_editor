import 'dart:convert';
import 'dart:io';

// One catalog and one shader body produce both native backends. Generated LUTs
// are package-authored RGB transforms, not third-party creative assets.
void main() {
  final catalog =
      jsonDecode(File('shaders/catalog.json').readAsStringSync()) as List;
  final body = File('shaders/effect_body.glsl').readAsStringSync();
  void write(String path, String contents) {
    File(path).parent.createSync(recursive: true);
    File(path).writeAsStringSync(contents);
  }

  String number(dynamic n) => (n as num).toDouble().toString();
  write(
    'lib/src/effects/catalog.g.dart',
    '''// Generated by tool/generate_effects.dart. Do not edit.
part of 'editor_effect_registry.dart';
const _definitions = <EditorEffectDefinition>[
${catalog.map((e) => 'EditorEffectDefinition(${jsonEncode(e['id'])}, ${jsonEncode(e['name'])}, {${(e['parameters'] as Map).entries.map((p) => '${jsonEncode(p.key)}: EffectParameter(${p.value.map(number).join(', ')})').join(', ')}}),').join('\n')}
];
''',
  );
  write(
    'android/src/main/kotlin/com/sachinlal/vn_editor/EffectCatalog.g.kt',
    '''// Generated by tool/generate_effects.dart. Do not edit.
package com.sachinlal.vn_editor
internal val effectSpecs = listOf(
${catalog.map((e) => 'EffectSpec(${jsonEncode(e['id'])}, listOf(${(e['parameters'] as Map).entries.map((p) => 'EffectParameter(${jsonEncode(p.key)}, ${p.value.map(number).join(', ')})').join(', ')}))').join(',\n')}
)
internal val effectBody = """
$body
"""
''',
  );
  write(
    'ios/vn_editor/Sources/vn_editor/EffectCatalog.g.swift',
    '''// Generated by tool/generate_effects.dart. Do not edit.
import Foundation
let effectSpecs: [EffectSpec] = [
${catalog.map((e) => 'EffectSpec(id: ${jsonEncode(e['id'])}, parameters: [${(e['parameters'] as Map).entries.map((p) => 'EffectParameter(name: ${jsonEncode(p.key)}, min: ${number(p.value[0])}, max: ${number(p.value[1])}, value: ${number(p.value[2])})').join(', ')}])').join(',\n')}
]
let effectBody = """
${body.replaceAll('vec2', 'float2').replaceAll('vec3', 'float3').replaceAll('vec4', 'float4')}
"""
''',
  );
  final bytes = <int>[];
  for (var preset = 0; preset < 4; preset++) {
    for (var g = 0; g < 17; g++) {
      for (var b = 0; b < 17; b++) {
        for (var r = 0; r < 17; r++) {
          final red = r / 16, green = g / 16, blue = b / 16;
          final rgb = switch (preset) {
            0 => [red * 1.05 + .03, green * 1.01, blue * .94],
            1 => [red * .94, green * 1.01, blue * 1.05 + .03],
            2 => [red * .9 + .08, green * .88 + .06, blue * .75 + .08],
            _ => [(red - .5) * 1.1 + .5, green, (blue - .5) * 1.1 + .53],
          };
          bytes.addAll([...rgb.map((v) => (v.clamp(0, 1) * 255).round()), 255]);
        }
      }
    }
  }
  for (final path in [
    'android/src/main/assets/vn_editor_luts.rgba',
    'ios/vn_editor/Sources/vn_editor/Resources/vn_editor_luts.rgba',
  ]) {
    File(path).parent.createSync(recursive: true);
    File(path).writeAsBytesSync(bytes);
  }
}
